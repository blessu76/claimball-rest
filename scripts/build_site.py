def breadcrumb_html(items):
    return '<nav class="crumbs" aria-label="breadcrumb">%s</nav>' % " › ".join(
        '<a href="%s">%s</a>' % (esc(h), esc(l)) if h else "<span>%s</span>" % esc(l) for h, l in items)


def breadcrumb_ld(items):
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": l, **({"item": url(h)} if h else {})} for i, (h, l) in enumerate(items)]}


def website_ld(lang, ctx):
    return {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": "Claimball", "inLanguage": lang,
            "publisher": {"@id": ORG_ID}}


def game_ld(lang, ctx):
    # no offers, no ratings, no release date: the game is not out yet
    return {"@type": "VideoGame", "@id": SITE + "/#game", "name": "Claimball", "url": url(path_home(lang)),
            "description": ctx.t(lang, "home_desc"), "inLanguage": lang, "genre": ["Sports", "Casual"],
            "applicationCategory": "GameApplication", "gamePlatform": ["iOS", "Android"],
            "image": SITE + OG_IMAGE, "creator": ORG, "publisher": {"@id": ORG_ID}}


def post_card(ctx, lang, p):
    d = p["langs"][lang]
    link = esc(path_post(lang, p["slug"]))
    return ('<a class="card post-card" href="%s"><div class="post-meta"><time datetime="%s">%s</time><span class="tag">%s</span></div>'
            '<div class="post-main"><h3>%s</h3><p>%s</p><span class="more">%s</span></div></a>') % (
        link, iso_time(p), fmt_date(p), esc(ctx.t(lang, "cat_" + p["category"])), esc(d["title"]), esc(d["description"]), esc(ctx.t(lang, "read_more")))


def posts_in(ctx, lang):
    return [p for p in ctx.posts if lang in p["langs"]]


