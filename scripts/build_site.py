def rfc822(d):
    return d.strftime("%a, %d %b %Y %H:%M:%S +0900")


def build_feed(ctx, lang):
    items = []
    for p in posts_in(ctx, lang):
        d = p["langs"][lang]
        items.append("<item><title>%s</title><link>%s</link><guid isPermaLink=\"true\">%s</guid><pubDate>%s</pubDate>"
                     "<category>%s</category><description>%s</description></item>" % (
                         esc(d["title"]), esc(url(path_post(lang, p["slug"]))), esc(url(path_post(lang, p["slug"]))),
                         rfc822(p["published"]), esc(p["category"]), esc(d["description"])))
    last = rfc822(ctx.posts[0]["published"]) if ctx.posts else rfc822(dt.datetime(2026, 10, 31, tzinfo=KST))
