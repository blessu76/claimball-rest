def fmt_date(p):
    return p["published"].strftime("%Y-%m-%d")


def iso_time(p):
    return p["published"].strftime("%Y-%m-%dT%H:%M:00+09:00")


def latest_post_date(ctx):
    return max([fmt_date(p) for p in ctx.posts] + [SITE_UPDATED])


def render(ctx, lang, *, path, title, desc, body, graph, alt, updated, og_type="website", noindex=False, hreflang=True, nav=""):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    name, og_loc, direction, short = LANGS[lang]
    canonical = url(path)
    head = ['<meta charset="utf-8">', '<meta name="viewport" content="width=device-width,initial-scale=1">',
            "<title>%s</title>" % esc(title), '<meta name="description" content="%s">' % esc(desc)]
    head.append('<meta name="robots" content="%s">' % ("noindex,follow" if noindex else "index,follow,max-image-preview:large"))
    head.append('<link rel="canonical" href="%s">' % esc(canonical))
    if hreflang and len(alt) > 1:
        for l, pth in alt.items():
            head.append('<link rel="alternate" hreflang="%s" href="%s">' % (l, esc(url(pth))))
        head.append('<link rel="alternate" hreflang="x-default" href="%s">' % esc(url(alt.get("en", next(iter(alt.values()))))))
    head += ['<meta property="og:type" content="%s">' % og_type, '<meta property="og:site_name" content="Claimball">',
             '<meta property="og:title" content="%s">' % esc(title), '<meta property="og:description" content="%s">' % esc(desc),
             '<meta property="og:url" content="%s">' % esc(canonical), '<meta property="og:locale" content="%s">' % og_loc,
             '<meta property="og:image" content="%s">' % (SITE + OG_IMAGE), '<meta property="og:image:width" content="1200">',
             '<meta property="og:image:height" content="630">', '<meta name="twitter:card" content="summary_large_image">',
             '<meta name="twitter:title" content="%s">' % esc(title), '<meta name="twitter:description" content="%s">' % esc(desc),
             '<meta name="twitter:image" content="%s">' % (SITE + OG_IMAGE),
             '<meta name="theme-color" content="#FBF8EE">', '<meta name="color-scheme" content="light">',
             '<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">',
             '<link rel="apple-touch-icon" href="/assets/icon-180.png">']
    if lang in MAIN_LANGS:
        head.append('<link rel="alternate" type="application/rss+xml" title="Claimball Journal (%s)" href="%s">' % (lang, path_feed(lang)))
    head.append('<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>')
    head.append('<link rel="stylesheet" href="%s">' % FONTS_URL)
    head.append('<link rel="stylesheet" href="/assets/claimball.css?v=%s">' % ASSET_V)
    if path == "/":
        head.append(langpick_script(ctx.root, ctx.langs))
    head.append('<script type="application/ld+json">%s</script>' % json.dumps({"@context": "https://schema.org", "@graph": graph},
                                                                            ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/"))
    switch = "".join('<a href="%s" hreflang="%s" lang="%s"%s aria-label="%s">%s</a>' % (
        esc(alt.get(l) or path_home(l)), l, l, ' aria-current="true"' if l == lang else "", esc(LANGS[l][0]), esc(LANGS[l][3])) for l in ctx.langs)
    navlinks = [(path_home(lang), t("nav_home"), "home"), (path_page(lang, "about"), t("nav_about"), "about"),
                (path_journal(lang), t("nav_journal"), "journal"), (path_releases(lang), t("nav_releases"), "releases"),
                (path_page(lang, "support"), t("nav_support"), "support")]
    nav_html = "".join('<a href="%s"%s>%s</a>' % (esc(h), ' aria-current="page"' if nav == k else "", esc(label)) for h, label, k in navlinks)
    header = ('<header class="site-header"><div class="bar"><a class="brand" href="%s" aria-label="Claimball">Claim<span>ball</span></a>'
              '<nav class="nav" aria-label="main">%s<span class="langsw" role="group" aria-label="%s">%s</span></nav></div></header>') % (
        esc(path_home(lang)), nav_html, esc(t("lang_label")), switch)
    foot_nav = [(path_home(lang), t("nav_home")), (path_page(lang, "about"), t("nav_about")), (path_journal(lang), t("nav_journal")),
                (path_releases(lang), t("nav_releases")), (path_page(lang, "support"), t("nav_support")),
                (path_page(lang, "privacy"), t("nav_privacy")), (path_page(lang, "terms"), t("nav_terms"))]
    foot_nav_html = "".join('<a href="%s">%s</a>' % (esc(h), esc(label)) for h, label in foot_nav)
