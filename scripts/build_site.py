def parse_front(text):
    m = re.match(r"^---\n(.*?)\n---[ \t]*\n?(.*)$", text, re.S)
    if not m:
        raise ValueError("no front matter")
    meta = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        k, sep, v = line.partition(":")
        if not sep:
            raise ValueError("bad front matter line: %r" % line)
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        meta[k.strip()] = v
    return meta, m.group(2).strip("\n")


def img_size(root, src):
    """(w, h) of a local PNG / JPEG / SVG, or None."""
    if not src.startswith("/"):
        return None
    p = Path(root) / src.lstrip("/")
    try:
        data = p.read_bytes()
    except OSError:
        return None
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", data[16:24])
    if data[:2] == b"\xff\xd8":  # JPEG: find the SOF marker
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1; continue
            mk = data[i + 1]
            if mk in (0xC0, 0xC1, 0xC2):
                h, w = struct.unpack(">HH", data[i + 5:i + 9])
                return w, h
            i += 2 + struct.unpack(">H", data[i + 2:i + 4])[0]
    if p.suffix == ".svg":
        m = re.search(rb'viewBox="[\d.\-]+ [\d.\-]+ ([\d.]+) ([\d.]+)"', data)
        if m:
            return int(float(m.group(1))), int(float(m.group(2)))
    return None


def inline(s):
    codes = []

    def stash(m):
        codes.append("<code>%s</code>" % esc(m.group(1)))
        return "\x00%d\x00" % (len(codes) - 1)

    s = re.sub(r"`([^`]+)`", stash, s)
    s = esc(s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)",
               lambda m: '<a href="%s"%s>%s</a>' % (m.group(2), ' rel="noopener"' if m.group(2).startswith("http") else "", m.group(1)), s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<![*\w])\*([^*\n]+)\*(?![*\w])", r"<em>\1</em>", s)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], s)


def markdown(text, root, heading_offset=0):
    lines = text.split("\n")
    out, i, n = [], 0, len(lines)
    para = []

    def flush():
        if para:
            out.append("<p>%s</p>" % inline(" ".join(x.strip() for x in para)))
            para.clear()

    while i < n:
        ln = lines[i]
        s = ln.strip()
        if not s:
            flush(); i += 1; continue
        if s.startswith("```"):
            flush(); i += 1; buf = []
            while i < n and not lines[i].strip().startswith("```"):
                buf.append(lines[i]); i += 1
            i += 1
            out.append("<pre><code>%s</code></pre>" % esc("\n".join(buf)))
            continue
        m = re.match(r"^(#{2,4})\s+(.*)$", s)
        if m:
            flush(); lvl = len(m.group(1)) + heading_offset
            out.append("<h%d>%s</h%d>" % (lvl, inline(m.group(2)), lvl)); i += 1; continue
        if re.match(r"^-{3,}$", s):
            flush(); out.append("<hr>"); i += 1; continue
        m = re.match(r"^!\[([^\]]*)\]\(([^)\s]+)\)$", s)
        if m:
            flush(); alt, src = m.group(1), m.group(2)
            size = img_size(root, src)
            dims = ' width="%d" height="%d"' % size if size else ""
            cap = ""
            if i + 1 < n and re.match(r"^\*[^*].*\*$", lines[i + 1].strip()):
                cap = "<figcaption>%s</figcaption>" % inline(lines[i + 1].strip()[1:-1]); i += 1
            out.append('<figure><img src="%s" alt="%s"%s loading="lazy" decoding="async">%s</figure>' % (esc(src), esc(alt), dims, cap))
            i += 1; continue
        if s.startswith(">"):
            flush(); buf = []
            while i < n and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip()); i += 1
            out.append("<blockquote>%s</blockquote>" % markdown("\n".join(buf), root))
            continue
        if re.match(r"^[-*]\s+", s) or re.match(r"^\d+\.\s+", s):
            flush(); ordered = bool(re.match(r"^\d+\.", s)); items = []
            while i < n and re.match(r"^(?:[-*]|\d+\.)\s+", lines[i].strip()):
                items.append(re.sub(r"^(?:[-*]|\d+\.)\s+", "", lines[i].strip())); i += 1
            tag = "ol" if ordered else "ul"
            out.append("<%s>%s</%s>" % (tag, "".join("<li>%s</li>" % inline(x) for x in items), tag))
            continue
        if s.startswith("|") and i + 1 < n and re.match(r"^\|?\s*:?-{2,}", lines[i + 1].strip()):
            flush(); rows = []
            while i < n and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")]); i += 1
            head, body = rows[0], rows[2:]
            t = "<thead><tr>%s</tr></thead>" % "".join("<th>%s</th>" % inline(c) for c in head)
            t += "<tbody>%s</tbody>" % "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % inline(c) for c in r) for r in body)
            out.append('<div class="table-wrap"><table>%s</table></div>' % t)
            continue
        para.append(ln); i += 1
    flush()
    return "\n".join(out)


# ---------------------------------------------------------------- loading
def load_i18n(root):
    d, errs = {}, []
    for f in sorted((Path(root) / "content" / "i18n").glob("*.json")):
        lang = f.stem
        if lang in ENDED:
            continue
        if lang not in LANGS:
            errs.append("i18n/%s.json: unknown language" % lang); continue
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except ValueError as ex:
            errs.append("i18n/%s.json: %s" % (lang, ex)); continue
        miss = [k for k in KEYS if not str(data.get(k, "")).strip()]
        extra = [k for k in data if k not in KEYS]
        if miss:
            errs.append("i18n/%s.json: missing %s" % (lang, ", ".join(miss)))
        if extra:
            errs.append("i18n/%s.json: unknown keys %s" % (lang, ", ".join(extra)))
        for k, v in data.items():
            errs += text_problems("i18n/%s.json %s" % (lang, k), str(v))
        if not miss:
            d[lang] = data
    return d, errs


def load_pages(root):
    pages, errs = {}, []
    for lang in LANGS:
        for slug in PAGE_SLUGS:
            f = Path(root) / "content" / "pages" / lang / (slug + ".md")
            if not f.is_file():
                continue
            try:
                meta, body = parse_front(f.read_text(encoding="utf-8"))
            except ValueError as ex:
                errs.append("%s: %s" % (f, ex)); continue
            for k in ("title", "description", "updated"):
                if not meta.get(k):
                    errs.append("%s/%s: missing %s" % (lang, f.name, k))
            if meta.get("updated") and not DATE_RE.match(meta["updated"]):
                errs.append("%s/%s: updated must look like 2026-10-31" % (lang, f.name))
            errs += text_problems("%s/%s" % (lang, slug), meta.get("title", "") + meta.get("description", "") + body)
            if lang not in MAIN_LANGS and meta.get("translation_of") not in MAIN_LANGS:
                errs.append("pages/%s/%s.md: translation_of: ko|en required" % (lang, slug))
            pages[(lang, slug)] = (meta, body)
    return pages, errs


def parse_published(v):
    m = PUB_RE.match(v)
    if not m:
        raise ValueError("published must look like 2026-10-31T18:00+09:00, got %r" % v)
    return dt.datetime(*map(int, m.groups()), tzinfo=KST)


FAQ_HEADINGS = {"en": "FAQ", "ko": "자주 묻는 질문"}  # the `faq_h` i18n value of the two original languages


def faq_items(body, heading):
    """[(question, answer)] from the `## <heading>` section of a post body: each `### question` followed by its answer paragraph(s)."""
    items, in_faq, q, ans = [], False, None, []
    for ln in body.split("\n"):
        s = ln.strip()
        m = re.match(r"^(#{2,4})\s+(.*)$", s)
        if m and len(m.group(1)) == 2:
            if in_faq and q is not None:
                items.append((q, " ".join(ans).strip()))
            in_faq, q, ans = (m.group(2).strip() == heading), None, []
            continue
        if not in_faq:
            continue
        if m and len(m.group(1)) == 3:
            if q is not None:
                items.append((q, " ".join(ans).strip()))
            q, ans = m.group(2).strip(), []
        elif q is not None and s:
            ans.append(s)
    if in_faq and q is not None:
        items.append((q, " ".join(ans).strip()))
    return [(a, re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", re.sub(r"[*`]", "", b))) for a, b in items]


def geo_problems(tag, lang, summary, body):
    errs = []
    if not summary.strip():
        errs.append("%s: front matter `summary:` (2-3 sentences that answer the post's question) is required" % tag)
    elif len(summary) > 480:
        errs.append("%s: summary is too long (%d > 480 characters)" % (tag, len(summary)))
    faq = faq_items(body, FAQ_HEADINGS[lang])
    if len(faq) < 2:
        errs.append("%s: needs a `## %s` section with at least 2 `### question` entries" % (tag, FAQ_HEADINGS[lang]))
    for q, a in faq:
        if not a:
            errs.append("%s: FAQ question %r has no answer" % (tag, q))
    return errs


def load_posts(root, now=None, include_dir="journal"):
    """-> (posts sorted newest first, errors). post = {slug, published, category, langs:{lang: {...}}}"""
    now = now or dt.datetime.now(KST)
    base = Path(root) / "content" / include_dir
    errs, posts = [], []
    if not base.is_dir():
        return posts, errs
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        slug = d.name
        if not SLUG_RE.match(slug):
            errs.append("%s: bad slug folder name" % slug); continue
        post = {"slug": slug, "langs": {}, "published": None, "category": None}
        for f in sorted(d.glob("*.md")):
            lang = f.stem
            tag = "%s/%s" % (slug, f.name)
            if lang in ENDED:
                continue
            if lang not in LANGS:
                errs.append("%s: unknown language" % tag); continue
            try:
                meta, body = parse_front(f.read_text(encoding="utf-8"))
            except ValueError as ex:
                errs.append("%s: %s" % (tag, ex)); continue
            miss = [k for k in REQUIRED_POST if not meta.get(k)]
            if miss:
                errs.append("%s: missing %s" % (tag, ", ".join(miss))); continue
            if meta["slug"] != slug:
                errs.append("%s: slug %r != folder" % (tag, meta["slug"]))
            if meta["lang"] != lang:
                errs.append("%s: lang %r != file name" % (tag, meta["lang"]))
            if meta["category"] not in CATEGORIES:
                errs.append("%s: category must be one of %s" % (tag, "/".join(CATEGORIES)))
            try:
                pub = parse_published(meta["published"])
            except ValueError as ex:
                errs.append("%s: %s" % (tag, ex)); continue
            if pub > now:
                errs.append("%s: published %s is in the future (now %s)" % (tag, meta["published"], now.strftime("%Y-%m-%dT%H:%M")))
            if post["published"] and pub != post["published"]:
                errs.append("%s: published differs between languages" % tag)
            post["published"] = post["published"] or pub
            post["category"] = post["category"] or meta["category"]
            if lang not in MAIN_LANGS and meta.get("translation_of") not in MAIN_LANGS:
                errs.append("%s: translation_of: ko|en required" % tag)
            if not body.strip():
                errs.append("%s: empty body" % tag)
            errs += text_problems(tag, meta["title"] + meta["description"] + meta.get("summary", "") + body)
            if meta.get("modified") and not PUB_RE.match(meta["modified"]):
                errs.append("%s: modified must look like 2026-11-03T21:05+09:00" % tag)
            if lang in MAIN_LANGS:  # GEO: the originals always carry a short answer and a FAQ (queue posts too, see queue_errors)
                errs += geo_problems(tag, lang, meta.get("summary", ""), body)
            post["langs"][lang] = {"title": meta["title"], "description": meta["description"], "body": body,
                                   "translation_of": meta.get("translation_of"), "keywords": meta.get("keywords", ""),
                                   "summary": meta.get("summary", ""), "modified": meta.get("modified", "")}
        if not post["langs"]:
            errs.append("%s: folder has no post files" % slug); continue
        for need in MAIN_LANGS:
            if need not in post["langs"]:
                errs.append("%s: %s original missing" % (slug, need))
        posts.append(post)
    posts.sort(key=lambda p: (p["published"] or now, p["slug"]), reverse=True)
    return posts, errs


def queue_errors(root):
    """Queued posts (content/queue/NN-slug/<lang>.md, no `published:` yet) must be publishable the day they are due."""
    errs = []
    q = Path(root) / "content" / "queue"
    seen = set()
    for d in sorted(p for p in q.iterdir() if p.is_dir()) if q.is_dir() else []:
        m = re.match(r"^(\d+)-([a-z0-9]+(?:-[a-z0-9]+)*)$", d.name)
        if not m:
            errs.append("queue/%s: folder must be NN-slug" % d.name); continue
        slug = m.group(2)
        if slug in seen or (Path(root) / "content" / "journal" / slug).exists():
            errs.append("queue/%s: slug already used" % d.name)
        seen.add(slug)
        langs = set()
        for f in sorted(d.glob("*.md")):
            if f.stem in ENDED:
                continue
            tag = "queue/%s/%s" % (d.name, f.name)
            try:
                meta, body = parse_front(f.read_text(encoding="utf-8"))
            except ValueError as ex:
                errs.append("%s: %s" % (tag, ex)); continue
            langs.add(f.stem)
            miss = [k for k in REQUIRED_POST if k != "published" and not meta.get(k)]
            if miss:
                errs.append("%s: missing %s" % (tag, ", ".join(miss)))
            if "published" in meta:
                errs.append("%s: must not carry `published:` (publish_post.py stamps it)" % tag)
            if meta.get("slug") != slug or meta.get("lang") != f.stem or f.stem not in LANGS:
                errs.append("%s: slug/lang do not match folder/file name" % tag)
            if meta.get("category") not in CATEGORIES:
                errs.append("%s: category must be one of %s" % (tag, "/".join(CATEGORIES)))
            if f.stem not in MAIN_LANGS and meta.get("translation_of") not in MAIN_LANGS:
                errs.append("%s: translation_of: ko|en required" % tag)
            errs += text_problems(tag, meta.get("title", "") + meta.get("description", "") + meta.get("summary", "") + body)
            if f.stem in MAIN_LANGS:
                errs += geo_problems(tag, f.stem, meta.get("summary", ""), body)
        for need in MAIN_LANGS:
            if need not in langs:
                errs.append("queue/%s: %s original missing" % (d.name, need))
    return errs


