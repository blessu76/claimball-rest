LEGACY_REDIRECTS = {"pt": ("pt-BR", ("", "about/", "privacy/", "support/", "terms/", "journal/", "journal/starting-claimball/"))}


def build_redirect(old, new, path):
    target = url("/%s/%s" % (new, path))
    head = ['<meta charset="utf-8">', '<meta name="viewport" content="width=device-width,initial-scale=1">',
            '<meta name="robots" content="noindex">', '<title>Claimball</title>',
            '<link rel="canonical" href="%s">' % esc(target),
            '<meta http-equiv="refresh" content="0; url=%s">' % esc(target)]
    body = '<p><a href="%s">Claimball</a></p>' % esc(target)
    return ("/%s/%sindex.html" % (old, path),
            "<!doctype html>\n<html lang=\"%s\">\n<head>\n%s\n</head>\n<body>\n%s\n</body>\n</html>\n" % (new, "\n".join(head), body))


def build_all(ctx):
    """-> {relative file path: text}"""
    files = {}

    def put(path, text):
        files[path.lstrip("/") + "index.html" if path.endswith("/") else path.lstrip("/")] = text

    for l in ctx.built:
        put(*build_home(ctx, l))
        for slug in PAGE_SLUGS:
            put(*build_page(ctx, l, slug))
        for pg in range(1, pages_count(len(posts_in(ctx, l))) + 1):
            put(*build_list(ctx, l, pg))
        for p in ctx.posts:
            if l in p["langs"]:
                put(*build_post(ctx, l, p))
    for old, (new, paths) in LEGACY_REDIRECTS.items():
        for path in paths:
            rel, text = build_redirect(old, new, path)
            files[rel.lstrip("/")] = text
    files["404.html"] = build_404(ctx)
    files["sitemap.xml"] = build_sitemap(ctx)
    files["robots.txt"] = build_robots()
    files["llms.txt"] = build_llms(ctx)
    for l in MAIN_LANGS:
        if l in ctx.langs:
            files[path_feed(l).lstrip("/")] = build_feed(ctx, l)
    for rel, text in files.items():  # which languages really have this page: decided from the finished file set
        if LANGPICK_MARK in text:
            have = [l for l in ctx.langs if l != "en" and "%s/%s" % (l, rel) in files]
            files[rel] = text.replace(LANGPICK_MARK, langpick_script(ctx.root, ctx.langs, have))
    return files


def clean(root):
    root = Path(root)
    for name in ["journal"] + list(PAGE_SLUGS) + [l for l in LANGS if l != "en"] + list(LEGACY_REDIRECTS):  # ENDED folders are kept as-is (policy 769ad15)
        d = root / name
        if d.is_dir():
            shutil.rmtree(d)
    for name in ("index.html", "404.html", "sitemap.xml", "robots.txt", "llms.txt"):
        f = root / name
        if f.is_file():
            f.unlink()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--check", action="store_true", help="validate sources only")
    ap.add_argument("--require-all", action="store_true", help="fail unless every language in LANGS is complete for every post")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    ctx, errs = make_ctx(root, require_all=a.require_all)
    if errs:
        print("build_site: %d problem(s)\n  %s" % (len(errs), "\n  ".join(errs)), file=sys.stderr)
        return 1
    files = build_all(ctx)
    if a.check:
        print("build_site: sources OK — %d language(s), %d post(s), %d file(s) would be written" % (len(ctx.langs), len(ctx.posts), len(files)))
        return 0
    clean(root)
    for rel, text in files.items():
        f = root / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
    print("build_site: wrote %d file(s) — %d language(s), %d post(s)" % (len(files), len(ctx.langs), len(ctx.posts)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
