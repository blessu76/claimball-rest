def build_home(ctx, lang):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    latest = posts_in(ctx, lang)[:3]
    plain, _, accent = t("hero_h1").partition("|")
    badges = ('<div class="badges" role="group" aria-label="%s"><span class="store"><small>App Store</small><b>%s</b></span>'
              '<span class="store"><small>Google Play</small><b>%s</b></span></div>') % (
        esc(t("store_aria")), esc(t("store_soon")), esc(t("store_soon")))
    cards = "".join('<article class="card feat">%s<h3>%s</h3><p>%s</p></article>' % (CARD_ICONS[i - 1], esc(t("card%d_h" % i)), esc(t("card%d_p" % i)))
                    for i in (1, 2, 3))
    news = ""
    if latest:
        news = ('<section class="section"><div class="sec-head"><h2>%s</h2><a class="more" href="%s">%s</a></div><div class="stack">%s</div></section>' % (
            esc(t("latest_h")), esc(path_journal(lang)), esc(t("all_posts")), "".join(post_card(ctx, lang, p) for p in latest)))
    body = ('<section class="hero"><div class="hero-text"><p class="perk">%s</p><h1>%s<span>%s</span></h1><p class="lead">%s</p>%s'
            '<p class="note">%s</p></div><div class="hero-art">%s</div></section>'
            '<section class="section" id="how"><h2>%s</h2><div class="grid three">%s</div></section>'
            '<section class="section"><div class="card rivals"><h2>%s</h2><p>%s</p></div></section>%s'
            '<section class="cta"><div class="cta-in"><div><h2>%s</h2><p>%s</p></div>%s</div></section>') % (
        esc(t("status_badge")), esc(plain), esc(accent), esc(t("hero_lead")), badges, esc(t("hero_note")), board_html(ctx, lang),
        esc(t("how_h")), cards, esc(t("rivals_h")), esc(t("rivals_p")), news, esc(t("cta_h")), esc(t("cta_p")), badges)
    alt = {l: path_home(l) for l in ctx.langs}
    graph = [ORG, website_ld(lang, ctx), game_ld(lang, ctx)]
    return path_home(lang), render(ctx, lang, path=path_home(lang), title=t("home_title"), desc=t("home_desc"), body=body,
                                   graph=graph, alt=alt, updated=latest_post_date(ctx), nav="home")


def build_page(ctx, lang, slug):
    meta, md = ctx.pages[(lang, slug)]
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    crumbs = [(path_home(lang), t("crumb_home")), (None, meta["title"])]
    ai = ""
    if lang not in MAIN_LANGS:
        ai = '<p class="ai-note">%s <a href="%s">%s</a></p>' % (esc(t("ai_note")), esc(path_page("ko" if meta.get("translation_of") == "ko" else "en", slug)), esc(t("ai_orig")))
    body = '%s<article class="prose"><h1>%s</h1>%s%s</article>' % (
        breadcrumb_html(crumbs), esc(meta["title"]), ai, markdown(ctx.sub(md), ctx.root))
    page_ld = {"@type": "AboutPage" if slug == "about" else "WebPage", "@id": url(path_page(lang, slug)) + "#page",
               "url": url(path_page(lang, slug)), "name": meta["title"], "description": meta["description"], "inLanguage": lang,
               "dateModified": meta["updated"], "isPartOf": {"@id": SITE + "/#website"}}
    if slug == "about":
        page_ld["about"] = {"@id": SITE + "/#game"}
    graph = [ORG, website_ld(lang, ctx), page_ld, breadcrumb_ld(crumbs)]
    if slug == "about":
        graph.append(game_ld(lang, ctx))
    alt = {l: path_page(l, slug) for l in ctx.langs if (l, slug) in ctx.pages}
    return path_page(lang, slug), render(ctx, lang, path=path_page(lang, slug), title="%s — Claimball" % meta["title"],
                                         desc=meta["description"], body=body, graph=graph, alt=alt, updated=meta["updated"],
                                         nav=slug if slug in ("about", "support") else "")


def build_releases(ctx, lang):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    crumbs = [(path_home(lang), t("crumb_home")), (None, t("releases_title"))]
    cards = []
    for e in ctx.releases:
        own = lang in e["notes"] and lang in e["title"] and lang in e["intro"]
        src = lang if own else "en"
        status = t("rel_status_" + e["status"])
        date = ' · <time datetime="%s">%s</time>' % (esc(e["date"]), esc(e["date"])) if e.get("date") else ""
        attrs = "" if own else ' lang="en" dir="ltr"'
        note = "" if own else '<p class="rel-fallback">%s</p>' % esc(t("rel_en_note"))
        cards.append('<article class="card release" id="%s"><p class="meta"><span class="tag">%s</span> %s%s</p>'
                     '<h2%s>%s</h2>%s<p%s>%s</p><ul%s>%s</ul></article>' % (
                         esc(e["id"]), esc(status), esc(e["version"]), date, attrs, esc(e["title"][src]), note, attrs, esc(e["intro"][src]), attrs,
                         "".join("<li>%s</li>" % inline(x) for x in e["notes"][src])))
    listing = "".join(cards) if cards else '<div class="card release"><p>%s</p></div>' % esc(t("releases_empty"))
    body = '%s<h1 class="page-h">%s</h1><p class="lead">%s</p><div class="releases">%s</div>' % (
        breadcrumb_html(crumbs), esc(t("releases_title")), esc(t("releases_desc")), listing)
    page_ld = {"@type": "CollectionPage", "@id": url(path_releases(lang)) + "#page", "url": url(path_releases(lang)),
               "name": t("releases_title"), "description": t("releases_desc"), "inLanguage": lang, "isPartOf": {"@id": SITE + "/#website"}}
    graph = [ORG, website_ld(lang, ctx), page_ld, breadcrumb_ld(crumbs)]
    alt = {l: path_releases(l) for l in ctx.langs}
    return path_releases(lang), render(ctx, lang, path=path_releases(lang), title="%s — Claimball" % t("releases_title"),
                                       desc=t("releases_desc"), body=body, graph=graph, alt=alt, updated=lastmod_releases(ctx), nav="releases")


def build_list(ctx, lang, page):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    items = posts_in(ctx, lang)
    total = pages_count(len(items))
    chunk = items[(page - 1) * PER_PAGE: page * PER_PAGE]
    crumbs = [(path_home(lang), t("crumb_home")), (None, t("journal_title"))]
    grid = '<div class="stack">%s</div>' % "".join(post_card(ctx, lang, p) for p in chunk) if chunk else '<p class="empty">%s</p>' % esc(t("empty"))
    pager = ""
    if total > 1:
        links = []
        if page > 1:
            links.append('<a class="btn ghost" rel="prev" href="%s">%s</a>' % (esc(path_journal(lang, page - 1)), esc(t("prev"))))
        links.append("<span>%s %d / %d</span>" % (esc(t("page")), page, total))
        if page < total:
            links.append('<a class="btn ghost" rel="next" href="%s">%s</a>' % (esc(path_journal(lang, page + 1)), esc(t("next"))))
        pager = '<nav class="pager" aria-label="pagination">%s</nav>' % "".join(links)
    rss = ' <a class="rss" href="%s">%s</a>' % (esc(path_feed(lang)), esc(t("rss"))) if lang in MAIN_LANGS else ""
    body = '%s<h1 class="page-h">%s<span>.</span></h1><svg class="squig" width="220" height="14" viewBox="0 0 220 14" fill="none" aria-hidden="true"><path d="M4 8 C30 2 50 12 80 7 S130 2 160 8 S200 11 216 5" stroke="#FFA726" stroke-width="5" stroke-linecap="round"/></svg><p class="lead">%s%s</p>%s%s' % (
        breadcrumb_html(crumbs), esc(t("journal_title")), esc(t("journal_desc")), rss, grid, pager)
    title = t("journal_title") + (" — %s %d" % (t("page"), page) if page > 1 else "") + " — Claimball"
    blog = {"@type": "Blog", "@id": url(path_journal(lang)) + "#blog", "url": url(path_journal(lang)), "name": t("journal_title"),
            "description": t("journal_desc"), "inLanguage": lang, "isPartOf": {"@id": SITE + "/#website"}, "publisher": {"@id": ORG_ID},
            "blogPost": [{"@type": "BlogPosting", "headline": p["langs"][lang]["title"], "url": url(path_post(lang, p["slug"])),
                          "datePublished": iso_time(p)} for p in chunk]}
    graph = [ORG, website_ld(lang, ctx), blog, breadcrumb_ld(crumbs)]
    alt = {l: path_journal(l) for l in ctx.langs} if page == 1 else {lang: path_journal(lang, page)}
    return path_journal(lang, page), render(ctx, lang, path=path_journal(lang, page), title=title, desc=t("journal_desc"), body=body,
                                            graph=graph, alt=alt, updated=latest_post_date(ctx), nav="journal", hreflang=(page == 1))


def build_post(ctx, lang, p):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    d = p["langs"][lang]
    path = path_post(lang, p["slug"])
    crumbs = [(path_home(lang), t("crumb_home")), (path_journal(lang), t("journal_title")), (None, d["title"])]
    avail = [l for l in ctx.langs if l in p["langs"]]
    alt = {l: path_post(l, p["slug"]) for l in avail}
    ai = ""
    src = d["translation_of"] if lang not in MAIN_LANGS else None
    if src:
        ai = '<p class="ai-note">%s <a href="%s">%s</a></p>' % (esc(t("ai_note")), esc(path_post(src, p["slug"])), esc(t("ai_orig")))
    others = "".join('<li><a href="%s" hreflang="%s" lang="%s">%s</a></li>' % (esc(alt[l]), l, l, esc(LANGS[l][0])) for l in avail if l != lang)
    same_lang = posts_in(ctx, lang)
    idx = next(i for i, x in enumerate(same_lang) if x["slug"] == p["slug"])
    older = same_lang[idx + 1] if idx + 1 < len(same_lang) else None
    newer = same_lang[idx - 1] if idx > 0 else None
    pn = ""
    if older or newer:
        pn = '<nav class="pager" aria-label="posts">%s%s</nav>' % (
            ('<a rel="prev" href="%s">← %s</a>' % (esc(path_post(lang, older["slug"])), esc(older["langs"][lang]["title"]))) if older else "<span></span>",
            ('<a rel="next" href="%s">%s →</a>' % (esc(path_post(lang, newer["slug"])), esc(newer["langs"][lang]["title"]))) if newer else "<span></span>")
    body = ('%s<article class="prose post"><header><p class="post-meta"><time datetime="%s">%s</time><span class="tag">%s</span></p><h1>%s</h1>'
            '<p class="lead">%s</p></header>%s%s</article>%s%s<p class="back"><a href="%s">← %s</a></p>') % (
        breadcrumb_html(crumbs), iso_time(p), fmt_time(p), esc(t("cat_" + p["category"])), esc(d["title"]), esc(d["description"]), ai,
        markdown(d["body"], ctx.root), pn,
        ('<aside class="langs"><h2>%s</h2><ul>%s</ul></aside>' % (esc(t("other_langs")), others)) if others else "",
        esc(path_journal(lang)), esc(t("back_journal")))
    posting = {"@type": "BlogPosting", "@id": url(path) + "#post", "mainEntityOfPage": url(path), "url": url(path),
               "headline": d["title"], "description": d["description"], "inLanguage": lang, "datePublished": iso_time(p),
               "dateModified": iso_time(p), "image": {"@type": "ImageObject", "url": SITE + OG_IMAGE, "width": 1200, "height": 630},
               "author": ORG, "publisher": {"@id": ORG_ID}, "isPartOf": {"@id": url(path_journal(lang)) + "#blog"},
               "about": {"@id": SITE + "/#game"}, "articleSection": p["category"]}
    if d["keywords"]:
        posting["keywords"] = d["keywords"]
    if src:
        posting["translationOfWork"] = {"@type": "BlogPosting", "url": url(path_post(src, p["slug"])), "inLanguage": src}
    graph = [ORG, website_ld(lang, ctx), posting, breadcrumb_ld(crumbs)]
    return path, render(ctx, lang, path=path, title="%s — Claimball" % d["title"], desc=d["description"], body=body, graph=graph,
                        alt=alt, updated=fmt_date(p), og_type="article", nav="journal")


